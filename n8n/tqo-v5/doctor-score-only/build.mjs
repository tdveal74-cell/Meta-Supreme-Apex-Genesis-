export const SCORE_ONLY_CONTRACT = [
  "  'SCORE ONLY PASS. This pass scores the draft and never repairs it. Nothing you return replaces a word of the title, the script, the description or the b-roll.',",
  "  'Diagnose and score exactly as the full pass would. Where the full pass would have returned REPAIRED, return NEEDS_REVISION and put the repair you would have made in notes.',",
  "  '',",
  "  'Return ONLY valid JSON, no fences:',",
  "  '{\"score\":0,\"verdict\":\"PASS or NEEDS_REVISION\",',",
  "  '\"preserved\":[\"what you would refuse to touch and why\"],',",
  "  '\"diagnosis\":\"the single highest-leverage problem, with the line that shows it\",',",
  "  '\"notes\":[\"specific, actionable, at most four\"]}',",
  "  '',",
  "  'PASS only when the draft is already sound as written. A high score never makes a broken draft PASS, and an unusual draft is not a broken one.'"
].join('\n');

const HEADER = [
  '// Build Doctor Prompt, score-only copy. Generated by',
  '// n8n/tqo-v5/doctor-score-only/build.mjs from the live node of TQO FINAL V5 at',
  '// the version live/manifest.json names. Every line is the live text except the',
  '// output contract at the end of the system prompt, which asks for a score and',
  '// a verdict of PASS or NEEDS_REVISION and no rewritten script, and the text',
  '// shown when the row stores no checklist.',
  ''
].join('\n');

export const LIVE_HYDRATE_FIELDS = 'const f = row.fields || row;';
export const SCORE_ONLY_HYDRATE_FIELDS = [
  '// Score-only copy. The DT shim builds fields from its MAP only, which has no',
  '// learning_objective and spells the b-roll column Broll Keywords, so the live',
  '// line, const f = row.fields || row, read neither and the doctor was told the',
  "// learning objective was none returned. The row's own columns are read too,",
  "// and the shim's names win where both exist.",
  'const f = { ...row, ...(row.fields || {}) };'
].join('\n');

export function scoreOnlyHydrate() {
  const body = live('script_hydrate_from_row.js');
  if (body.split(LIVE_HYDRATE_FIELDS).length !== 2) {
    throw new Error('The live fields line was not found exactly once in live/script_hydrate_from_row.js. Re-pin it and review this build.');
  }
  return body.replace(LIVE_HYDRATE_FIELDS, () => SCORE_ONLY_HYDRATE_FIELDS);
}

// Ruled by Tee 2026-10-24 after the first run: the hand-loaded rows store no
// checklist, so the live line told the doctor the checklist was "(none
// returned)" and row 49 was held on a checklist its script speaks. With none
// stored, the doctor is now told to judge the spoken steps in the script. The
// same wording went live in TQO FINAL V5 the same day.
export const LIVE_CHECKLIST_EMPTY = ".join(' ') : '(none returned)')";
export const SCORE_ONLY_CHECKLIST_EMPTY = ".join(' ') : '(not stored on this row; judge the spoken steps in the script itself)')";

export function scoreOnlyPrompt() {
  const live0 = live('build_doctor_prompt.js');
  if (live0.split(LIVE_CHECKLIST_EMPTY).length !== 2) {
    throw new Error('The live empty checklist text was not found exactly once in live/build_doctor_prompt.js. Re-pin it and review this build.');
  }
  const body = live0.replace(LIVE_CHECKLIST_EMPTY, () => SCORE_ONLY_CHECKLIST_EMPTY);
  const at = body.indexOf(LIVE_CONTRACT);
  if (at === -1 || body.indexOf(LIVE_CONTRACT, at + 1) !== -1) {
    throw new Error('The live output contract was not found exactly once in live/build_doctor_prompt.js. The live prompt has changed; re-pin it and review this build.');
  }
  return HEADER + body.slice(0, at) + SCORE_ONLY_CONTRACT + body.slice(at + LIVE_CONTRACT.length);
}

const code = (name, js, pos, extra = {}) => ({ kind: 'node', name, type: 'n8n-nodes-base.code', version: 2, position: pos,
  parameters: { mode: 'runOnceForAllItems', language: 'javaScript', jsCode: js }, extra });
const rowById = (table, rowId) => ({ resource: 'row', operation: 'get',
  dataTableId: { __rl: true, mode: 'id', value: table }, matchType: 'allConditions',
  filters: { conditions: [{ keyName: 'id', condition: 'eq', keyValue: rowId }] }, returnAll: true });
const scripted = (table) => ({ resource: 'row', operation: 'get',
  dataTableId: { __rl: true, mode: 'id', value: table }, matchType: 'allConditions',
  filters: { conditions: [{ keyName: 'status', condition: 'eq', keyValue: 'Scripted' }] }, returnAll: true });
const pinnedHttp = (name, file, pos) => {
  const n = JSON.parse(live(file));
  const extra = {};
  for (const [k, v] of Object.entries(n.settings)) if (v !== null && v !== undefined) extra[k] = v;
  return { kind: 'node', name, type: n.type, version: n.typeVersion, position: pos, parameters: n.parameters, credentials: n.credentials, extra };
};

